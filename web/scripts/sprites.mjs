// Spread a tile's particles apart: each connected shape keeps its form but moves out in
// proportion to its position, on a canvas `factor` times larger (density drops by factor²).
const spread = (art, factor) => {
  const rows = art.trim().split('\n').map((r) => [...r]);
  const h = rows.length;
  const w = rows[0].length;
  const out = Array.from({ length: Math.round(h * factor) }, () =>
    Array(Math.round(w * factor)).fill('.'),
  );
  const seen = new Set();
  for (let y = 0; y < h; y++) {
    for (let x = 0; x < w; x++) {
      if (rows[y][x] === '.' || seen.has(`${x},${y}`)) continue;
      // Collect this shape (4-connected), then place it at its scaled top-left.
      const shape = [];
      const stack = [[x, y]];
      seen.add(`${x},${y}`);
      while (stack.length) {
        const [cx, cy] = stack.pop();
        shape.push([cx, cy]);
        for (const [nx, ny] of [[cx + 1, cy], [cx - 1, cy], [cx, cy + 1], [cx, cy - 1]]) {
          if (rows[ny]?.[nx] && rows[ny][nx] !== '.' && !seen.has(`${nx},${ny}`)) {
            seen.add(`${nx},${ny}`);
            stack.push([nx, ny]);
          }
        }
      }
      const dx = Math.floor(Math.min(...shape.map(([sx]) => sx)) * (factor - 1));
      const dy = Math.floor(Math.min(...shape.map(([, sy]) => sy)) * (factor - 1));
      for (const [sx, sy] of shape) out[sy + dy][sx + dx] = rows[sy][sx];
    }
  }
  return out.map((r) => r.join('')).join('\n');
};

