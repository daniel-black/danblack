for (const [name, [palette, art]] of Object.entries(sprites)) {
  const rows = art.trim().split('\n');
  const w = rows[0].length;
  const rects = [];
  rows.forEach((row, y) => {
    if (row.length !== w) throw new Error(`${name} row ${y} is ${row.length} wide, expected ${w}`);
    for (let x = 0; x < w; ) {
      const c = row[x];
      let end = x;
      while (row[end] === c) end++;
      if (c !== '.') rects.push(`<rect x="${x}" y="${y}" width="${end - x}" height="1" fill="${palette[c]}"/>`);
      x = end;
    }
  });
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${rows.length}" width="${w}" height="${rows.length}" shape-rendering="crispEdges">${rects.join('')}</svg>\n`;
  writeFileSync(`${out}/${name}.svg`, svg);
  console.log(name, `${w}x${rows.length}`, rects.length, 'rects');
}
